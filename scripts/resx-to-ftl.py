#!/usr/bin/env python3
"""Converts ShareX `.resx` translations into Fluent bundles (M6 D9).

usage: resx-to-ftl.py <dir with Strings.resx and Strings.<lang>.resx> <locales dir>

Keys stay ShareX's resource names (`HotkeyType_RectangleRegion`), so `laqta-ui` looks them up by the
same name. `{0}`-style placeholders become Fluent variables `{ $arg0 }`. Only strings are converted;
entries with a `type` (images, binary) are skipped. Run it offline on a ShareX checkout; nothing here
downloads anything.
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ID = re.compile(r"^[A-Za-z][A-Za-z0-9_-]*$")
PLACEHOLDER = re.compile(r"\{(\d+)(?::[^}]*)?\}")


def read(path: Path) -> dict[str, str]:
    out = {}
    for data in ET.parse(path).getroot().iter("data"):
        name = data.get("name", "")
        value = data.find("value")
        if data.get("type") or value is None or not ID.match(name):
            continue
        out[name] = value.text or ""


    return out


def escape(text: str) -> str:
    def literal(m: re.Match) -> str:
        return "{ $arg" + m.group(1) + " }"

    parts = []
    last = 0
    for m in PLACEHOLDER.finditer(text):
        parts.append(text[last : m.start()].replace("{", '{"{"}').replace("}", '{"}"}'))
        parts.append(literal(m))
        last = m.end()
    parts.append(text[last:].replace("{", '{"{"}').replace("}", '{"}"}'))
    text = "".join(parts)
    lines = text.replace("\r\n", "\n").split("\n")
    out = []
    for line in lines:
        # Fluent treats these as syntax at the start of a continuation line.
        if line[:1] in ("[", "*", "."):
            line = '{"' + line[0] + '"}' + line[1:]
        out.append(line)
    if len(out) == 1:
        v = out[0]
        if v.startswith(" ") or not v:
            v = '{""}' + v if v else '{""}'
        return " " + v
    return "\n" + "\n".join("    " + (l if l else '{""}') for l in out)


def write(path: Path, entries: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = ["# Generated by scripts/resx-to-ftl.py from ShareX's translations (GPL-3.0). Do not edit by hand."]
    for key in sorted(entries):
        body.append(f"{key} ={escape(entries[key])}")
    path.write_text("\n".join(body) + "\n", encoding="utf-8")


def main() -> None:
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    english = read(src / "Strings.resx")
    write(dst / "en" / "laqta.ftl", english)
    for f in sorted(src.glob("Strings.*.resx")):
        lang = f.name[len("Strings.") : -len(".resx")]
        entries = {k: v for k, v in read(f).items() if k in english and v.strip()}
        write(dst / lang / "laqta.ftl", entries)
        print(f"{lang}: {len(entries)}/{len(english)}")


if __name__ == "__main__":
    main()
